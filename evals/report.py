"""Results tables for docs/phases/phase-5-report.md and the headline numbers in summary.json.

    report.write(results)                 # replaces the text between the two markers
    report.summary(results, today)        # the public scorecard's data

The prose around the markers is written by hand; everything between them is generated, so a
rerun of `make evals` is what the report shows.
"""

from __future__ import annotations

import datetime as dt
import json
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Final

from networth.config import REPO

REPORT: Final = REPO / "docs" / "phases" / "phase-5-report.md"
START: Final = "<!-- results:start (generated by `make evals`, do not edit by hand) -->"
END: Final = "<!-- results:end -->"
LEAN_WORDS: Final = {"leans-up": "leans toward", "leans-down": "leans against",
                     "no-pattern": "no clear pattern"}  # fmt: skip


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def ratio(hits: int, n: int) -> str:
    return f"{hits} of {n}" if n else "none yet"


def table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |"
              for r in rows]  # fmt: skip
    return "\n".join(lines)


def lean_table(rows: Sequence[Mapping]) -> str:
    return table(
        ["Stated lean", "Statements", "Later episodes", "Later hit rate", "Stated hit rate",
         "Baseline", "Leans that held"],
        [(r["lean"], r["statements"], r["episodes"], pct(r["later_rate"]), pct(r["stated_rate"]),
          pct(r["baseline"]),
          f"{r['held']} of {r['judged']}" if r["judged"] is not None else "not judged")
         for r in rows],
    )  # fmt: skip


def calibration_table(rows: Sequence[Mapping]) -> str:
    return table(
        ["Stated chance of the likelier outcome", "Later episodes", "It happened",
         "Mean stated chance", "Mean baseline chance"],
        [(r["bucket"], r["episodes"], f"{r['happened']} ({pct(r['happened_rate'])})",
          pct(r["stated_mean"]), pct(r["baseline_mean"])) for r in rows],
    )  # fmt: skip


def by_cutoff_table(w: Mapping) -> str:
    """Leaning statements per cutoff: how many, and how their later episodes went."""
    rows = []
    for cutoff in w["cutoffs"]:
        for lean in ("leans-up", "leans-down"):
            group = [s for s in w["scored"] if s["cutoff"] == cutoff and not s["weak"]
                     and s["lean"] == lean]  # fmt: skip
            outs = [o for s in group for o in s["outcomes"]]
            rows.append((cutoff, LEAN_WORDS[lean], len(group),
                         ratio(sum(o["hit"] for o in outs), len(outs)),
                         len({o["episode_id"] for o in outs})))  # fmt: skip
    return table(["Cutoff", "Lean", "Statements", "Later hits", "Distinct episodes"], rows)


def walkforward_md(w: Mapping) -> str:
    rows = sorted(w["per_row"], key=lambda r: (r["type"], r["asset"]))
    per_row = table(
        ["Type", "Asset", "Era", "In-sample", "In-sample rate", "Baseline", "Gap", "Lean",
         "Later", "Later rate", "Later baseline", "Later gap"],
        [(r["type"], r["asset"], r["era"], ratio(r["in_hits"], r["in_n"]), pct(r["in_rate"]),
          pct(r["in_baseline"]), f"{100 * r['in_gap']:+.0f} pts", LEAN_WORDS[r["lean"]],
          ratio(r["out_hits"], r["out_n"]), pct(r["out_rate"]), pct(r["out_baseline"]),
          "n/a" if r["out_gap"] is None else f"{100 * r['out_gap']:+.0f} pts") for r in rows],
    )  # fmt: skip
    distinct = {o["episode_id"] for s in w["scored"] for o in s["outcomes"]}
    return "\n\n".join([
        f"### Walk-forward\n\nCutoffs {', '.join(w['cutoffs'])}; each statement is scored on "
        f"the episodes up to the next cutoff, the last block ending the day before {w['end']}. "
        f"{w['statements']} statements, {sum(len(s['outcomes']) for s in w['scored'])} later "
        f"episode scores over {len(distinct)} distinct episodes.",
        "**By stated lean**\n\n" + lean_table(w["by_lean"]),
        "**Leaning statements by cutoff**\n\n" + by_cutoff_table(w),
        "**Calibration (strong statements)**\n\n" + calibration_table(w["calibration"]),
        f"**Every row with at least 8 episodes before 2022 ({len(rows)} rows)**\n\n" + per_row,
    ])  # fmt: skip


def vault_md(v: Mapping | None) -> str:
    if v is None:
        return "### Vault\n\nNot scored yet."
    scored = [r for r in v["rows"] if r["vault_n"]]
    strong = [r for r in scored if not r["weak"]]
    rows = table(
        ["Type", "Asset", "Said before 2022", "Baseline", "Lean", "Vault", "Vault rate", "Held"],
        [(r["type"], r["asset"], ratio(r["stated_hits"], r["stated_n"]), pct(r["baseline"]),
          "weak signal" if r["weak"] else LEAN_WORDS[r["lean"]],
          ratio(r["vault_hits"], r["vault_n"]), pct(r["vault_rate"]),
          {True: "held", False: "did not hold", None: "no lean"}[r["held"]])
         for r in sorted(strong, key=lambda r: (r["type"], r["asset"]))],
    )  # fmt: skip
    crash = f" Rerun after a crash: {v['after_crash']}." if v.get("after_crash") else ""
    return "\n\n".join([
        f"### Vault\n\nScored once at {v['run_at']} on plan commit `{v['plan_commit'][:7]}`."
        f"{crash} {len(v['rows'])} rows had a pre-2022 statement; {len(scored)} have vault "
        f"episodes, {len(strong)} of them strong.",
        "**By stated lean**\n\n" + lean_table(v["by_lean"]),
        "**Calibration (strong statements)**\n\n" + calibration_table(v["calibration"]),
        "**Every strong row with vault episodes**\n\n" + rows,
    ])  # fmt: skip


def news_md(n: Mapping | None) -> str:
    if n is None:
        return "### News judge\n\nNot run yet."
    p, j = n["pipeline"], n["judge_alone"]
    head = table(
        ["Measure", "Precision", "Recall", "Right", "False", "Missed"],
        [("Watcher pipeline (rule, judge, freshness)", pct(p["precision"]), pct(p["recall"]),
          p["tp"], p["fp"], p["fn"]),
         ("Judge alone, every row", pct(j["precision"]), pct(j["recall"]), j["tp"], j["fp"],
          j["fn"])],
    )  # fmt: skip
    kinds = table(["Kind", "Rows", "Rule confirmed", "Predicted an event", "Right"],
                  [(k, v.get("rows", 0), v.get("rule_confirmed", 0), v.get("predicted_event", 0),
                    v.get("right", 0)) for k, v in n["by_kind"].items()])  # fmt: skip
    fc = table(["Row", "Kind", "Label", "Predicted", "Headline", "Publishers", "Judge's reason"],
               [(f["id"], f["kind"], f["label"], f["predicted"], f["headline"],
                 ", ".join(f["publishers"]), f["judge"].get("reason", ""))
                for f in n["false_confirms"]]) if n["false_confirms"] else "None."  # fmt: skip
    missed = table(["Row", "Label", "Predicted", "Confirmed by rule", "Why"],
                   [(m["id"], m["label"], m["predicted"], m["confirmed"],
                     m["reject_reason"] or m["judge"].get("reason", "")) for m in n["missed"]]
                   ) if n["missed"] else "None."  # fmt: skip
    ja, jv = n["judge_type_accuracy"], n["jev_type_accuracy"]
    return "\n\n".join([
        f"### News judge\n\n{n['rows']} labelled stories ({n['positives']} real events of a "
        f"type), regions {json.dumps(n['regions'])}.",
        head, "**By kind**\n\n" + kinds,
        f"**Every false confirm ({len(n['false_confirms'])})**\n\n" + fc,
        f"**Every missed event ({len(n['missed'])})**\n\n" + missed,
        f"**Jev as a second picker.** Type accuracy over every row: judge {ja['right']} of "
        f"{ja['n']} ({pct(ja['accuracy'])}), Jev {jv['right']} of {jv['n']} "
        f"({pct(jv['accuracy'])}), Jev answered {n['jev_answered']}. At least as accurate: "
        f"{'yes' if n['jev_at_least_as_accurate'] else 'no'}.",
        f"**Cost and latency.** ${n['cost_usd']:.4f} for the run. Judge call median "
        f"{n['judge_ms_median'] / 1000:.1f} s, p90 {n['judge_ms_p90'] / 1000:.1f} s. Jev median "
        f"{(n['jev_ms_median'] or 0) / 1000:.1f} s.",
    ])  # fmt: skip


def words_md(w: Mapping | None) -> str:
    if w is None:
        return "### Words\n\nNot run yet."
    cats = table(["Category", "Messages", "Passed", "No advice or score", "No invented number",
                  "Right language"],
                 [(k, v["n"], f"{v.get('pass', 0)} ({pct(v.get('pass', 0) / v['n'])})",
                   v.get("advice_ok", 0), v.get("numbers_ok", 0), v.get("lang_ok", 0))
                  for k, v in w["by_category"].items()])  # fmt: skip
    fails = "\n\n".join(
        f"**{i}. {f['category']}**, expected `{f['expected_lang']}`, intent "
        f"`{f.get('intent')}`, sent `{f.get('used')}`.\n\n"
        f"- Message: {f['message']}\n- Reply: {(f.get('reply') or f.get('error') or '')}\n"
        f"- Checks: advice ok {f['checks']['advice_ok']}, numbers ok "
        f"{f['checks']['numbers_ok']} {f['checks']['invented'] or ''}, language ok "
        f"{f['checks']['lang_ok']} (judge says `{(f.get('grade') or {}).get('language')}`)\n"
        f"- Judge quote: {(f.get('grade') or {}).get('quote', '')}"
        for i, f in enumerate(w["failures"], 1)) or "None."  # fmt: skip
    g = w["by_grade"]
    return "\n\n".join([
        f"### Words\n\n{w['passed']} of {w['messages']} replies passed all three grades "
        f"({pct(w['passed'] / w['messages'])}). By grade: no advice or score {g['advice_ok']}, "
        f"no invented number {g['numbers_ok']}, right language {g['lang_ok']}. What went out: "
        f"{json.dumps(w['used'])}. Intents picked: {json.dumps(w['intents'])}. "
        f"Cost ${w['cost_usd']:.4f}.",
        cats, f"**Every failure ({len(w['failures'])})**\n\n" + fails,
    ])  # fmt: skip


def trace_md(t: Mapping | None) -> str:
    if t is None:
        return "### Number trace\n\nNot run yet."
    shown = "\n\n".join(
        f"**{m['kind']} · {m['type']} · {m['lang']}**\n\n```\n{m['text']}\n```\n\n"
        + table(["Number", "Field"], [(f"{x['number']:g}", x["path"] or "UNMAPPED")
                                      for x in m["mapping"]])
        for m in t["shown"])  # fmt: skip
    unmapped = table(["Type", "Kind", "Lang", "Number"],
                     [(u["type"], u["kind"], u["lang"], f"{u['number']:g}")
                      for u in t["unmapped"]]) if t["unmapped"] else "None."  # fmt: skip
    return "\n\n".join([
        f"### Number trace\n\n{t['messages']} messages ({t['errors']} could not be built), "
        f"{t['numbers']} numbers, {t['figures']} of them figures: {t['engine']} engine fields, "
        f"{t['event']} event dates, "
        f"{t['profile']} profile fields, {t['name']} inside asset names, "
        f"{len(t['unmapped'])} unmapped. Trace rate "
        f"{pct(t['trace_rate'])}; {t['messages_fully_traced']} messages fully traced. What went "
        f"out: {json.dumps(t['used'])}. Cost ${t['cost_usd']:.4f}.",
        "**Unmapped numbers**\n\n" + unmapped, shown,
    ])  # fmt: skip


def spend_md(usd: float | None) -> str:
    said = "not measured (no data/)" if usd is None else f"${usd:.2f}"
    return f"### Spend\n\nPhase 5 model spend: {said} of $15."


def render(results: Mapping) -> str:
    spend = results.get("spend_usd")
    parts = [
        walkforward_md(results["walkforward"]),
        vault_md(results.get("vault")),
        news_md(results.get("news")),
        words_md(results.get("words")),
        trace_md(results.get("trace")),
        spend_md(spend),
    ]
    return "\n\n".join(parts)


def write(results: Mapping, path: Path = REPORT) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else f"{START}\n{END}\n"
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    path.write_text(f"{head}{START}\n\n{render(results)}\n\n{END}{tail}", encoding="utf-8")


def _lean(rows: Sequence[Mapping], label: str) -> Mapping | None:
    return next((r for r in rows if r["lean"] == label), None)


def summary(results: Mapping, today: dt.date) -> dict:
    w, v = results["walkforward"], results.get("vault")
    n, wd, t = results.get("news"), results.get("words"), results.get("trace")

    def leans(block: Mapping) -> dict:
        return {k: {f: r[f] for f in ("statements", "episodes", "later_rate", "stated_rate",
                                       "baseline", "held", "judged")}
                for k, label in (("toward", "History leans toward"),
                                 ("against", "History leans against"))
                if (r := _lean(block["by_lean"], label))}  # fmt: skip

    return {
        "date": today.isoformat(),
        "calibration": {"walk_forward": {"cutoffs": w["cutoffs"], "end": w["end"],
                                         "leans": leans(w), "buckets": w["calibration"]}},
        "vault": None if v is None else {"plan_commit": v["plan_commit"], "run_at": v["run_at"],
                                         "leans": leans(v), "buckets": v["calibration"]},
        "news_judge": None if n is None else {"stories": n["rows"], "events": n["positives"],
                                              **{k: n["pipeline"][k] for k in
                                                 ("precision", "recall", "tp", "fp", "fn")}},
        "no_advice": None if wd is None else {
            "messages": wd["messages"], "passed": wd["passed"],
            "pass_rate": round(wd["passed"] / wd["messages"], 4),
            "advice_or_score_free": wd["by_grade"]["advice_ok"]},
        "number_trace": None if t is None else {"messages": t["messages"],
                                                "numbers": t["numbers"],
                                                "trace_rate": t["trace_rate"]},
        "spend_usd": results.get("spend_usd"),
    }  # fmt: skip
